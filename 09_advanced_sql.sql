PROMPT ===== VIEW 1: v_active_listeners =====
CREATE VIEW v_active_listeners AS
SELECT u.user_id, u.name, u.country, s.plan_name, s.end_date
FROM   Users u
JOIN   Subscriptions s ON s.user_id = u.user_id
WHERE  s.status = 'Active'
AND    TRUNC(SYSDATE) BETWEEN s.start_date AND s.end_date;
SELECT * FROM v_active_listeners ORDER BY end_date;

