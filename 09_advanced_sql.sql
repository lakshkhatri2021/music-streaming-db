PROMPT ===== BUILT-IN FUNCTIONS: string, numeric and date =====
SELECT UPPER(name) AS upper_name, LENGTH(name) AS name_len,
       SUBSTR(email, 1, INSTR(email, '@') - 1) AS email_user,
       ROUND(MONTHS_BETWEEN(SYSDATE, join_date), 1) AS months_member,
       TO_CHAR(join_date, 'Day, DD Mon YYYY') AS joined
FROM   Users
WHERE  user_id <= 4
ORDER  BY user_id;
SELECT MIN(duration_sec) AS shortest_sec, MAX(duration_sec) AS longest_sec,
       ROUND(AVG(duration_sec), 1) AS avg_sec, SUM(duration_sec) AS catalogue_sec,
       COUNT(DISTINCT genre) AS genres
FROM   Songs;

