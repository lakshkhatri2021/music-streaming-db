PROMPT ===== JOINS: RIGHT, CROSS and SELF =====
PROMPT RIGHT JOIN: every artist with the number of songs played (including artists with none)
SELECT a.name AS artist, COUNT(p.play_id) AS plays
FROM   Play_History p
JOIN   Songs s ON s.song_id = p.song_id
RIGHT  JOIN Artists a ON a.artist_id = s.artist_id
GROUP  BY a.name
ORDER  BY plays, a.name
FETCH  FIRST 5 ROWS ONLY;
PROMPT CROSS JOIN: every plan offered in every country we have users in
SELECT c.country, p.plan_name
FROM  (SELECT DISTINCT country FROM Users) c
CROSS JOIN (SELECT DISTINCT plan_name FROM Subscriptions) p
ORDER BY c.country, p.plan_name;
PROMPT SELF JOIN: pairs of users from the same country who joined on the same day
SELECT a.name AS user_1, b.name AS user_2, a.join_date
FROM   Users a
JOIN   Users b ON a.country = b.country AND a.join_date = b.join_date AND a.user_id < b.user_id
ORDER  BY a.join_date;

