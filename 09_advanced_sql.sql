PROMPT ===== VIEW 2: v_artist_earnings (aggregated, so not updatable) =====
CREATE VIEW v_artist_earnings AS
SELECT a.artist_id, a.name AS artist, COUNT(r.payment_id) AS months_paid,
       NVL(SUM(r.amount), 0) AS total_rs
FROM   Artists a
LEFT   JOIN Royalty_Payments r ON r.artist_id = a.artist_id
GROUP  BY a.artist_id, a.name;
SELECT artist, months_paid, total_rs FROM v_artist_earnings ORDER BY total_rs DESC FETCH FIRST 5 ROWS ONLY;
