PROMPT ===== SET OPERATIONS =====
PROMPT UNION: users who have ever subscribed to Premium or Family
SELECT u.name FROM Users u JOIN Subscriptions s ON s.user_id = u.user_id WHERE s.plan_name = 'Premium'
UNION
SELECT u.name FROM Users u JOIN Subscriptions s ON s.user_id = u.user_id WHERE s.plan_name = 'Family'
ORDER BY 1;
PROMPT INTERSECT: users who played songs in both September and October
SELECT u.name FROM Users u JOIN Play_History p ON p.user_id = u.user_id
WHERE  p.played_at >= DATE '2026-09-01' AND p.played_at < DATE '2026-10-01'
INTERSECT
SELECT u.name FROM Users u JOIN Play_History p ON p.user_id = u.user_id
WHERE  p.played_at >= DATE '2026-10-01' AND p.played_at < DATE '2026-11-01'
ORDER BY 1;
PROMPT MINUS: artists with songs who were never paid a royalty
SELECT name FROM Artists WHERE artist_id IN (SELECT artist_id FROM Songs)
MINUS
SELECT a.name FROM Artists a JOIN Royalty_Payments r ON r.artist_id = a.artist_id
ORDER BY 1;

