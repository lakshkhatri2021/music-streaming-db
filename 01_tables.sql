-- =====================================================================
-- Music Streaming Platform  |  01_tables.sql
-- Creates the 8 tables with primary keys, foreign keys and constraints.
-- Safe to re-run: drops the tables first if they already exist.
-- =====================================================================
SET SERVEROUTPUT ON
SET FEEDBACK ON

-- ---------- Drop old tables (children first) ----------
BEGIN
  FOR t IN (SELECT 'PLAYLIST_SONGS' tn FROM dual UNION ALL
            SELECT 'PLAYLISTS'        FROM dual UNION ALL
            SELECT 'ROYALTY_PAYMENTS' FROM dual UNION ALL
            SELECT 'PLAY_HISTORY'     FROM dual UNION ALL
            SELECT 'SONGS'            FROM dual UNION ALL
            SELECT 'ARTISTS'          FROM dual UNION ALL
            SELECT 'SUBSCRIPTIONS'    FROM dual UNION ALL
            SELECT 'USERS'            FROM dual) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.tn || ' CASCADE CONSTRAINTS PURGE';
      DBMS_OUTPUT.PUT_LINE('Dropped ' || t.tn);
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;   -- -942 = table does not exist
    END;
  END LOOP;
END;
/

-- ---------- 1. Users ----------
CREATE TABLE Users (
  user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  name       VARCHAR2(60)  NOT NULL,
  email      VARCHAR2(100) NOT NULL,
  country    VARCHAR2(40),
  join_date  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_users       PRIMARY KEY (user_id),
  CONSTRAINT uq_users_email UNIQUE (email)
);

-- ---------- 2. Subscriptions ----------
CREATE TABLE Subscriptions (
  sub_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id     NUMBER       NOT NULL,
  plan_name   VARCHAR2(10) NOT NULL,
  price_paid  NUMBER(8,2)  NOT NULL,
  start_date  DATE DEFAULT SYSDATE NOT NULL,
  end_date    DATE         NOT NULL,
  status      VARCHAR2(10) DEFAULT 'Active' NOT NULL,
  CONSTRAINT pk_subscriptions PRIMARY KEY (sub_id),
  CONSTRAINT fk_sub_user      FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
  CONSTRAINT ck_sub_plan      CHECK (plan_name IN ('Basic', 'Premium', 'Family')),
  CONSTRAINT ck_sub_status    CHECK (status IN ('Active', 'Expired', 'Cancelled')),
  CONSTRAINT ck_sub_price     CHECK (price_paid >= 0),
  CONSTRAINT ck_sub_dates     CHECK (end_date > start_date)
);

-- ---------- 3. Artists ----------
CREATE TABLE Artists (
  artist_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  name                VARCHAR2(60) NOT NULL,
  country             VARCHAR2(40),
  royalty_per_stream  NUMBER(6,2)  NOT NULL,
  CONSTRAINT pk_artists     PRIMARY KEY (artist_id),
  CONSTRAINT ck_artist_rate CHECK (royalty_per_stream > 0)
);

-- ---------- 4. Songs ----------
CREATE TABLE Songs (
  song_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  artist_id     NUMBER        NOT NULL,
  title         VARCHAR2(100) NOT NULL,
  album_title   VARCHAR2(100),
  genre         VARCHAR2(30),
  duration_sec  NUMBER(4)     NOT NULL,
  play_count    NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT pk_songs          PRIMARY KEY (song_id),
  CONSTRAINT fk_song_artist    FOREIGN KEY (artist_id) REFERENCES Artists(artist_id),
  CONSTRAINT ck_song_duration  CHECK (duration_sec > 0),
  CONSTRAINT ck_song_playcount CHECK (play_count >= 0)
);

-- ---------- 5. Play_History ----------
CREATE TABLE Play_History (
  play_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id         NUMBER    NOT NULL,
  song_id         NUMBER    NOT NULL,
  played_at       DATE DEFAULT SYSDATE NOT NULL,
  seconds_played  NUMBER(5) NOT NULL,
  CONSTRAINT pk_play_history PRIMARY KEY (play_id),
  CONSTRAINT fk_play_user    FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_play_song    FOREIGN KEY (song_id) REFERENCES Songs(song_id) ON DELETE CASCADE,
  CONSTRAINT ck_play_seconds CHECK (seconds_played >= 0)
);

-- ---------- 6. Royalty_Payments ----------
CREATE TABLE Royalty_Payments (
  payment_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  artist_id      NUMBER       NOT NULL,
  period_month   DATE         NOT NULL,   -- always the 1st of the month
  total_streams  NUMBER       NOT NULL,
  amount         NUMBER(10,2) NOT NULL,
  paid_on        DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_royalty_payments PRIMARY KEY (payment_id),
  CONSTRAINT fk_royalty_artist   FOREIGN KEY (artist_id) REFERENCES Artists(artist_id),
  CONSTRAINT uq_royalty_month    UNIQUE (artist_id, period_month),
  CONSTRAINT ck_royalty_streams  CHECK (total_streams >= 0),
  CONSTRAINT ck_royalty_amount   CHECK (amount >= 0)
);

-- ---------- 7. Playlists ----------
CREATE TABLE Playlists (
  playlist_id  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  user_id      NUMBER       NOT NULL,
  name         VARCHAR2(60) NOT NULL,
  created_on   DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_playlists     PRIMARY KEY (playlist_id),
  CONSTRAINT fk_playlist_user FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);

-- ---------- 8. Playlist_Songs ----------
CREATE TABLE Playlist_Songs (
  playlist_id  NUMBER NOT NULL,
  song_id      NUMBER NOT NULL,
  added_on     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_playlist_songs PRIMARY KEY (playlist_id, song_id),
  CONSTRAINT fk_ps_playlist    FOREIGN KEY (playlist_id) REFERENCES Playlists(playlist_id) ON DELETE CASCADE,
  CONSTRAINT fk_ps_song        FOREIGN KEY (song_id)     REFERENCES Songs(song_id) ON DELETE CASCADE
);

-- ---------- Check: list the tables and their constraints ----------
SET LINESIZE 200 PAGESIZE 100
COLUMN table_name      FORMAT A18
COLUMN constraint_name FORMAT A22
COLUMN type            FORMAT A12
SELECT table_name, constraint_name,
       DECODE(constraint_type, 'P', 'PRIMARY KEY', 'R', 'FOREIGN KEY',
                               'U', 'UNIQUE', 'C', 'CHECK') AS type
FROM   user_constraints
WHERE  table_name IN ('USERS','SUBSCRIPTIONS','ARTISTS','SONGS','PLAY_HISTORY',
                      'ROYALTY_PAYMENTS','PLAYLISTS','PLAYLIST_SONGS')
AND    constraint_name NOT LIKE 'SYS%'
ORDER  BY table_name, type;
